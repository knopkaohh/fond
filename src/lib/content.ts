export function findPage(slug: string) {
  return pages.find((page) => page.slug === slug);
}

export const searchIndex = [
  ...pages.map((page) => ({
    title: page.title,
    href: `/${page.slug}`,
    text: page.blocks
      .map((block) => {
        if (block.type === "list") return block.items.join(" ");
        if (block.type === "cards") return block.items.map((item) => `${item.title} ${item.text}`).join(" ");
        return block.text;
      })
      .join(" "),
  })),
  ...news.map((item) => ({
    title: item.title,
    href: `/novosti/${item.slug}`,
    text: `${item.excerpt} ${item.body.join(" ")}`,
  })),
  ...stories.map((item) => ({
    title: item.title,
    href: "/istorii-detey",
    text: item.lead,
  })),
];
